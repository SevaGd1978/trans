function fold(s: string): string {
  return s.toLowerCase().replace(/ё/g, "е");
}

export function extractPlace(raw: string): string {
  const original = raw.replace(/\s+/g, " ").trim();
  if (!original) return "";
  let s = original.replace(/^г\.\s*/i, "");
  const n = fold(s);
  const aliases = [...CITY_ALIASES].sort((a, b) => b[0].length - a[0].length);
  for (const [alias, city] of aliases) {
    if (n.includes(fold(alias))) return city;
  }
  s = s.replace(/^[\d\s./\\-]+/, "").trim().replace(/^г\.\s*/i, "");
  s = s.split(/\s+(?:ул\.|улица|пер\.|пр-т|проспект|квартал|стр\.|д\.)/i)[0]?.trim() ?? s;
  s = s.replace(/[\\/]+$/g, "").trim();
  return s || original;
}
